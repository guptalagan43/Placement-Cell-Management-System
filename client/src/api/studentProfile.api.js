// Student Profile API client: wraps the /students HTTP calls for profile management.
const API_BASE = import.meta.env.VITE_API_BASE ?? '/api'

async function handleResponse(res) {
  const data = await res.json().catch(() => ({}))
  if (!res.ok) {
    const err = new Error(data.message ?? 'Request failed')
    err.status = res.status
    err.code = data.code
    err.details = data.details
    throw err
  }
  return data
}

// Get student's own profile
export async function getSelfProfile() {
  const res = await fetch(`${API_BASE}/students/me/profile`, {
    method: 'GET',
    headers: { 'Content-Type': 'application/json' },
    credentials: 'include',
  })
  return handleResponse(res)
}

// Update student's own profile
export async function updateSelfProfile(data) {
  const res = await fetch(`${API_BASE}/students/me/profile`, {
    method: 'PUT',
    headers: { 'Content-Type': 'application/json' },
    credentials: 'include',
    body: JSON.stringify(data),
  })
  return handleResponse(res)
}

export default { getSelfProfile, updateSelfProfile }
